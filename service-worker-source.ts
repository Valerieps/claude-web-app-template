/**
 * The service worker that makes the installed app open without internet (ADR-005).
 *
 * `vite.config.ts` writes it to `dist/sw.js` after every production build, with the list of the
 * built files and a version taken from their contents. It keeps its own copy of those files and
 * serves them first; it touches only GET requests to the app's own origin, so it never opens a
 * connection that `network-policy.ts` does not allow.
 *
 * A new deploy reaches the person on the second opening: the browser finds a new `sw.js`, the new
 * worker downloads the new files and takes over once every tab of the app is closed. It never
 * swaps files under an open page.
 */

export const SERVICE_WORKER_FILE = 'sw.js';

/** Built files that are not served to the browser, or that the worker handles another way. */
const NOT_CACHED = new Set(['_headers', '_redirects', SERVICE_WORKER_FILE, 'index.html']);

/**
 * The URLs to keep, relative to the worker, from the built files (paths with `/`). `index.html` is kept as `./`: the server redirects
 * `/index.html` to `/`, and a redirected response cannot answer a navigation.
 */
export function precacheUrls(builtFiles: readonly string[]): string[] {
  const files = builtFiles.filter((file) => !NOT_CACHED.has(file));
  return ['./', ...[...files].sort().map((file) => `./${file}`)];
}

export function serviceWorkerSource(version: string, builtFiles: readonly string[]): string {
  return `// Generated by vite.config.ts from service-worker-source.ts (ADR-005). Do not edit.
const CACHE = ${JSON.stringify(`app-${version}`)};
const FILES = ${JSON.stringify(precacheUrls(builtFiles))};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith('app-') && key !== CACHE).map((key) => caches.delete(key)))),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  // Every page of the single-page app is the same index.html, kept as './'.
  const key = request.mode === 'navigate' ? './' : request;
  event.respondWith(
    caches
      .open(CACHE)
      .then((cache) => cache.match(key))
      .then((cached) => cached || fetch(request)),
  );
});
`;
}
